import { webkit, devices } from "playwright";
const b = await webkit.launch({ headless: true });
const ctx = await b.newContext({ ...devices["iPhone 15"] });
await ctx.addCookies([{ name: "burin", value: "5eed1234.1", url: "http://127.0.0.1:8080" }]);
const p = await ctx.newPage();
await p.goto("http://127.0.0.1:8080/");
await p.waitForTimeout(6000);
const { width } = devices["iPhone 15"].viewport;
await p.touchscreen.tap(width - 40, 34);
await p.waitForTimeout(800);
await p.touchscreen.tap(width / 2 + 40, 525);
await p.waitForTimeout(500);
const before = await p.evaluate(() => ({ active: document.activeElement?.tagName, ta: document.querySelector("textarea")?.value }));
await p.keyboard.type("pizza");
await p.waitForTimeout(800);
const after = await p.evaluate(() => ({ active: document.activeElement?.tagName, ta: document.querySelector("textarea")?.value }));
console.log({ before, after });
await p.screenshot({ path: "shots/keys.png", clip: { x: 0, y: 470, width: 393, height: 190 } });
await b.close();
